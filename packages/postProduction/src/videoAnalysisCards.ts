// 视频分析配方卡：读一条参考视频、把它拆成可核对的证据。
//
// 为什么放在卡库里：Agent 手上原本没有任何「读参考视频」的手段，
// 而技能文档要求它「先逐帧拆解成手法清单」—— 那条规则此前是空的。
// 把分析也做成卡，Agent 就有了和后期卡同一种检索方式：
// 想做某件事，先查卡库有没有现成的做法，没有才自己写。
//
// 与另两套卡的差别（必须在目录里说清，否则 Agent 会拿它当 ffmpeg 滤镜用）：
//   · ffmpeg 卡 / HTML 卡 → 产出**画面**，是"要做什么效果"
//   · 分析卡 → 产出**证据**，是"先看清现有素材里发生了什么"
// 所以分析卡不写 `filters`，也就不能被 ffmpeg 直接执行；它描述的是**读素材的动作**。
//
// 本包约束：不得依赖任何 node 内置模块 —— 这里只放纯数据，取帧/探测由调用方做。

/** 分析卡要读什么素材。 */
export type AnalysisInput = "视频" | "音频" | "词表";

/** 分析产出的证据种类（与 useCard / 分析节点对齐）。 */
export type AnalysisEvidence =
  /** 时长、分辨率、帧率、编码、是否含音轨 */
  | "媒体信息"
  /** 指定时刻的画面帧（可选烧上时间码与词上下文） */
  | "证据帧"
  /** 区间采样的网格图，用于一眼看完整段 */
  | "帧网格"
  /** 相邻帧变化候选与分数（只报候选，不判定为"镜头"） */
  | "边界候选"
  /** 词级时间戳（每个词有开始/结束秒） */
  | "词级时间"
  /** 按一句话定位到它的证据帧 */
  | "短语定位";

/**
 * 一张分析配方卡。
 *
 * ACT: 刻意**不含** filters / secondInput —— 这两项是 ffmpeg 卡的执行契约，
 * 分析卡不产出画面，带上它们会让 Agent 以为可以喂给 ffmpeg。
 */
export interface AnalysisRecipeCard {
  /** 卡标识（小驼峰），进提示词与产物命名。 */
  slug: string;
  title: string;
  category: "素材读取" | "语音" | "定位";
  /** 一句话说清「这是什么」。 */
  oneliner: string;
  inputs: AnalysisInput[];
  /** 产出哪些证据。 */
  evidence: AnalysisEvidence[];
  /**
   * 这张卡存在的理由 / 什么时候必须用它。
   * 写清"不用它会怎样"，因为 Agent 最常见的失败是跳过取证直接下结论。
   */
  why: string;
  /** 已知坑。 */
  pitfalls: string[];
  /** 落位自检：做完了该核什么。 */
  checks: string[];
}

